export function emptyItem(fields = []) {
  const item = {};
  fields.forEach((field) => {
    if (field.type === 'stringList' || field.type === 'objectList') item[field.key] = [];
    else if (field.type === 'checkbox') item[field.key] = false;
    else item[field.key] = '';
  });
  return item;
}
